async def all_releases(workspace_path: str | None = None) -> list[ReleaseRecord]:
    """Every release record, unfiltered by default — for platform-wide evaluation
    (Phase 8), not the "show the last few in a chat prompt" use recent_releases() serves.
    An unbounded query is fine at this project's scale (one local user's task history);
    revisit with pagination if that stops being true."""
    async with SessionLocal() as session:
        query = select(ReleaseRecord).order_by(ReleaseRecord.created_at.asc())
        if workspace_path is not None:
            query = query.where(ReleaseRecord.workspace_path == workspace_path)
        result = await session.execute(query)
        return list(result.scalars())
